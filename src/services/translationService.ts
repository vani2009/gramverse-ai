/**
 * Clean segment translator: translates complete phrases without substring mangling
 */
export function translateString(text: string, targetLang: SupportedLanguage): string {
  if (!text || typeof text !== 'string' || targetLang === 'en') {
    return text;
  }

  const trimmed = text.trim();
  if (!trimmed) return text;

  // 1. Direct exact match in phrase dictionary
  if (PHRASE_DICTIONARY[trimmed] && PHRASE_DICTIONARY[trimmed][targetLang]) {
    return text.replace(trimmed, PHRASE_DICTIONARY[trimmed][targetLang]);
  }

  // 2. Case-insensitive exact match
  const lower = trimmed.toLowerCase();
  for (const [phrase, transMap] of Object.entries(PHRASE_DICTIONARY)) {
    if (phrase.toLowerCase() === lower && transMap[targetLang]) {
      return text.replace(trimmed, transMap[targetLang]);
    }
  }

  // 3. Multi-word phrase containment match (only on complete sub-phrases > 3 chars)
  let result = text;
  for (const [phrase, transMap] of Object.entries(PHRASE_DICTIONARY)) {
    if (phrase.length > 5 && transMap[targetLang] && result.includes(phrase)) {
      result = result.split(phrase).join(transMap[targetLang]);
    }
  }

  return result;
}

/**
 * Trigger official Google Translate client-side translation
 */
export function triggerGoogleTranslate(langCode: SupportedLanguage): void {
  try {
    if (typeof document === 'undefined') return;

    if (langCode === 'en') {
      document.cookie = 'googtrans=; expires=Thu, 01 Jan 1970 00:00:00 UTC; path=/;';
      document.cookie = `googtrans=; expires=Thu, 01 Jan 1970 00:00:00 UTC; domain=${window.location.hostname}; path=/;`;
      const select = document.querySelector('.goog-te-combo') as HTMLSelectElement | null;
      if (select) {
        select.value = 'en';
        select.dispatchEvent(new Event('change'));
      }
      return;
    }

    const cookieVal = `/en/${langCode}`;
    document.cookie = `googtrans=${cookieVal}; path=/;`;
    document.cookie = `googtrans=${cookieVal}; domain=${window.location.hostname}; path=/;`;

    const select = document.querySelector('.goog-te-combo') as HTMLSelectElement | null;
    if (select) {
      select.value = langCode;
      select.dispatchEvent(new Event('change'));
    }
  } catch (err) {
    console.warn('Google Translate sync:', err);
  }
}

/**
 * Detect Indian language from text Unicode characters
 */
export function detectIndianLanguageFromText(text: string): SupportedLanguage {
  if (!text || !text.trim()) return 'en';
  
  for (const ch of text) {
    const code = ch.charCodeAt(0);
    // Devanagari (Hindi / Marathi)
    if (code >= 0x0900 && code <= 0x097F) {
      if (text.includes('आहे') || text.includes('नाही') || text.includes('करणे') || text.includes('झाले') || text.includes('ग्रामसेवक')) {
        return 'mr';
      }
      return 'hi';
    }
    // Gujarati
    if (code >= 0x0A80 && code <= 0x0AFF) return 'gu';
    // Bengali / Assamese
    if (code >= 0x0980 && code <= 0x09FF) return 'bn';
    // Gurmukhi (Punjabi)
    if (code >= 0x0A00 && code <= 0x0A7F) return 'pa';
    // Odia
    if (code >= 0x0B00 && code <= 0x0B7F) return 'or';
    // Tamil
    if (code >= 0x0B80 && code <= 0x0BFF) return 'ta';
    // Telugu
    if (code >= 0x0C00 && code <= 0x0C7F) return 'te';
    // Kannada
    if (code >= 0x0C80 && code <= 0x0CFF) return 'kn';
    // Malayalam
    if (code >= 0x0D00 && code <= 0x0D7F) return 'ml';
  }
  
  return 'en';
}

export function translateTextSmart(text: string, targetLang: SupportedLanguage): string {
  return translateString(text, targetLang);
}
